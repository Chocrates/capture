#!/usr/bin/env python3
"""Fail when the Kotlin side starts deciding things.

The conflict rules in §6 were property-tested across two milestones on the
assumption that there is exactly one implementation of them. A second one in
Kotlin would not be a duplicate — it would be the one nobody exercises, and it
would diverge silently, because both sides look correct in isolation and
nothing compares them.

So Kotlin renders and handles lifecycle. Everything else goes through
`capture-ffi`, which is the same code the desktop runs.

This is the `unwired` lesson in another language: the failure is not that the
wrong thing is written, it is that the wrong thing is written *and looks fine*.
A person reviewing a date calculation in a UI file has no reason to object
unless they happen to remember that the fold already does it.

Deliberately crude, and deliberately loud about what it cannot see. It matches
names and shapes, not semantics; a determined reimplementation will get past
it. What it catches is the ordinary case — somebody reaching for a familiar
Kotlin API because crossing the boundary felt like a detour.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "android"

# Generated by uniffi from the built library. It contains whatever the Rust
# surface contains, and editing it is already forbidden by it being generated.
GENERATED = "uniffi/"

# What Kotlin must not do, and why each one matters here rather than in
# general. The message is the point: a rule whose reason is not on screen at
# the moment it fires gets suppressed rather than obeyed.
FORBIDDEN = [
    (
        r"\bjava\.time\b|\bLocalDate\b|\bLocalDateTime\b|\bZonedDateTime\b|\bZoneId\b",
        "date and time arithmetic. §3.5 and the time model decide what a day is, "
        "what a recurrence expands to, and which timezone a note belongs to. Two "
        "answers to those questions is a calendar that disagrees with itself.",
    ),
    (
        r"\bCalendar\.getInstance\b|\bSimpleDateFormat\b",
        "date arithmetic through the older APIs. Same reason.",
    ),
    (
        r"\.toSlug\(|\bfun slugify|\bfun makeSlug",
        "slug generation. A slug is a note's permanent name and is derived from "
        "the capture in a way every replica must agree on.",
    ),
    (
        r"\bfun (merge|resolveConflict|reconcile)\b",
        "conflict resolution. §6's rules decide which of two concurrent edits "
        "wins, and they are property-tested on the assumption there is one "
        "implementation.",
    ),
    (
        r"\bRRULE\b|\bfun expandRecurrence\b",
        "recurrence expansion. capture-time owns what a rule produces, "
        "including the daylight-saving cases nobody remembers.",
    ),
    (
        r"\bSQLiteDatabase\b|\bandroid\.database\b|\bRoom\b",
        "talking to the store directly. The projection is derived data with a "
        "schema that is rebuilt rather than migrated, and a second reader would "
        "pin a shape that is meant to be free to change.",
    ),
]


def main() -> int:
    if not APP.exists():
        print("  no android/ yet — nothing to check")
        return 0

    sources = [
        p
        for p in APP.rglob("*.kt")
        if GENERATED not in str(p.relative_to(ROOT)) and "/build/" not in str(p)
    ]

    if not sources:
        print("  no hand-written Kotlin yet — nothing to check")
        return 0

    found = []
    for path in sources:
        for number, line in enumerate(path.read_text().splitlines(), 1):
            # A comment explaining why something is forbidden is not a
            # violation of it.
            if line.lstrip().startswith(("//", "*", "/*")):
                continue
            for pattern, why in FORBIDDEN:
                if re.search(pattern, line):
                    found.append((path.relative_to(ROOT), number, line.strip(), why))

    if not found:
        print(f"  {len(sources)} Kotlin file(s), none of them deciding anything")
        return 0

    print("  Kotlin is deciding something the core already decides:")
    for path, number, line, why in found:
        print(f"\n    {path}:{number}")
        print(f"      {line[:100]}")
        print(f"      This is {why}")
    print()
    print("  Ask capture-ffi for it. If the surface has no way to ask,")
    print("  that is the thing to change — not this file.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
