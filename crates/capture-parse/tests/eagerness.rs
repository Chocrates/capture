#[test]
#[ignore = "a measurement, not an assertion"]
fn how_often_the_near_miss_fires() {
    let mut offered = Vec::new();
    let mut lists = 0;

    for text in CORPUS {
        if list_of(text).is_some() {
            lists += 1;
        }
        if near_miss(text).is_some() {
            offered.push(*text);
        }
    }

    println!(
        "\n  {} captures, {lists} of them already lists\n  offered a near miss: {} ({:.1}%)\n",
        CORPUS.len(),
        offered.len(),
        100.0 * offered.len() as f64 / CORPUS.len() as f64,
    );
    for t in &offered {
        println!("    {t}");
    }
    println!();
}

/// The line that must hold whatever the rate turns out to be.
#[test]
fn the_offer_never_fires_on_something_already_a_list() {
    for text in CORPUS {
        if near_miss(text).is_some() {
            assert!(
                list_of(text).is_none(),
                "offered a near miss on a capture that is already a list: {text:?}"
            );
        }
    }
}

